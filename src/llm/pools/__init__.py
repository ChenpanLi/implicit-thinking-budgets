"""The item pools: one JSONL file of atomic items per dataset.

    python -m llm.pools gsm8k

writes ``$RUN_DIR/datasets/gsm8k.jsonl`` and its ``.manifest.json``. Six pools are
built from the Hugging Face Hub at a pinned revision (one module each in this
package); integrals and onewordqa were generated by us and ship with the repository
under ``datasets/<dataset>/``, so for those the entrypoint copies the shipped file.

Every record carries a stable ``q-NNNN`` (or ``atom-NNNN``) id that every batch and
every run refers to, so a rebuilt pool must be byte-identical to the one the runs
were made on. The entrypoint therefore never overwrites a pool that differs from the
rebuild unless told to.
"""
from __future__ import annotations

import importlib

# dataset -> module in this package that builds it from the Hub
HUB_BUILDERS = {
    "gpqa-diamond": "gpqa",
    "gsm8k": "gsm8k",
    "math500": "math500",
    "mmlu": "mmlu",
    "strategyqa": "strategyqa",
    "aime": "aime",
}


def build(dataset: str) -> tuple[list[dict], dict]:
    """The records and the manifest of one Hub-built pool."""
    module = importlib.import_module(f"llm.pools.{HUB_BUILDERS[dataset]}")
    return module.build()
